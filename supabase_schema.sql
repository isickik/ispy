-- Run this in Supabase SQL Editor.
-- Supabase Auth manages user identity. Keep Row Level Security enabled.
create table if not exists public.signals (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    strategy text not null,
    side text not null,
    expiry date,
    strike numeric,
    entry_price numeric,
    stop_price numeric,
    target_price numeric,
    signal_score integer,
    spy_price numeric,
    reason text,
    market_timestamp text,
    created_at timestamptz not null default now()
);

create table if not exists public.paper_trades (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    strategy text not null,
    side text not null,
    strike numeric not null,
    expiry date not null,
    entry_price numeric not null,
    contracts integer not null default 1,
    status text not null default 'OPEN',
    exit_price numeric,
    pnl numeric,
    notes text,
    created_at timestamptz not null default now(),
    closed_at timestamptz
);

alter table public.signals enable row level security;
alter table public.paper_trades enable row level security;

drop policy if exists "Users read own signals" on public.signals;
create policy "Users read own signals" on public.signals
for select using (auth.uid() = user_id);
drop policy if exists "Users insert own signals" on public.signals;
create policy "Users insert own signals" on public.signals
for insert with check (auth.uid() = user_id);

drop policy if exists "Users read own trades" on public.paper_trades;
create policy "Users read own trades" on public.paper_trades
for select using (auth.uid() = user_id);
drop policy if exists "Users insert own trades" on public.paper_trades;
create policy "Users insert own trades" on public.paper_trades
for insert with check (auth.uid() = user_id);
drop policy if exists "Users update own trades" on public.paper_trades;
create policy "Users update own trades" on public.paper_trades
for update using (auth.uid() = user_id) with check (auth.uid() = user_id);

